echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  Benchmark 3: Quad Revolution Solve (4 simultaneous)"
echo "═══════════════════════════════════════════════════════════════════"
echo ""
cargo bench --bench lambert_benchmark -- --quiet quad_rev 2>&1 | grep -A 3 "quad_rev"

echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  Benchmark 4: Swarm 8-Revolution Solve ✨"
echo "═══════════════════════════════════════════════════════════════════"
echo ""
cargo bench --bench lambert_benchmark -- --quiet swarm_8rev 2>&1 | grep -A 3 "swarm_8rev"

echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  Benchmark 5: Batch TOF Evaluation (Scalar vs SIMD)"
echo "═══════════════════════════════════════════════════════════════════"
echo ""
cargo bench --bench lambert_benchmark -- --quiet "batch_tof" 2>&1 | grep -E "batch_tof|time:"

