echo "  • Single rev:    ~426,621 solve-sets/second"
echo "  • Dual rev:      ~231,481 solve-sets/second"
echo "  • Quad rev:      ~120,337 solve-sets/second"
echo "  • Swarm 8-rev:   ~61,350 solve-sets/second ✅"
echo ""
echo "Key Achievements:"
echo "  ✓ Sub-millisecond performance: 16.3 µs for 8 revolutions"
