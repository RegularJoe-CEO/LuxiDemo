echo "Platform: $(uname -m) - $(uname -s)"
echo "CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2 | xargs)"
echo "Cores: $(nproc)"
echo ""
echo "Building optimized release binary..."
cargo build --release --quiet 2>/dev/null || cargo build --release

echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  Benchmark 1: Single Revolution Solve"
echo "═══════════════════════════════════════════════════════════════════"
echo ""
cargo bench --bench lambert_benchmark -- --quiet single_rev 2>&1 | grep -A 3 "single_rev"

echo ""
echo "═══════════════════════════════════════════════════════════════════"
echo "  Benchmark 2: Dual Revolution Solve"
echo "═══════════════════════════════════════════════════════════════════"
